#!/usr/bin/env python3
"""Regenerate LVGL ARGB8888 icons from the approved native-size design PNGs."""
from pathlib import Path
from PIL import Image
root=Path(__file__).resolve().parents[1]
source=root/'design/home-cat-soft-20260917'
out=root/'main/memo_icons.c'
assets=[('cat','cat-native.png'),('paw','paw-native.png'),('fish','fish-native.png')]
lines=['// Generated by scripts/generate_ui_icons.py from design/home-cat-soft-20260917/.', '#include "memo_icons.h"', '']
for name,filename in assets:
 im=Image.open(source/filename).convert('RGBA');w,h=im.size
 pixels=im.tobytes()
 raw=bytearray()
 for n in range(0,len(pixels),4):
  r,g,b,a=pixels[n:n+4];raw.extend((b,g,r,a))
 lines.extend([f'static const uint8_t {name}_pixels[] = {{'])
 for n in range(0,len(raw),16):lines.append('    '+', '.join(f'0x{b:02x}' for b in raw[n:n+16])+',')
 lines.extend(['};',f'const lv_image_dsc_t memo_icon_{name} = {{',f'    .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888, .w = {w}, .h = {h}, .stride = {w*4} }},',f'    .data_size = sizeof({name}_pixels), .data = {name}_pixels,','};',''])
out.write_text('\n'.join(lines))
print(out)

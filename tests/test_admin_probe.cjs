"use strict";
const assert = require("node:assert/strict");
const report = require("../server-relay/static/probe-report.js");
const base = {validation:"pass",tls:"not_checked",auth:"not_checked",delivery:"not_checked",end_to_end:"not_checked"};
let rendered = report({mode:"tls",providers:{qwen:{...base,tls:"pass"}}});
assert.equal(rendered.success,true);
assert.match(rendered.text,/TLS 连接通过/);
assert.match(rendered.text,/鉴权未检查/);
assert.doesNotMatch(rendered.text,/鉴权通过/);
rendered = report({mode:"end_to_end",providers:{qwen:{...base,tls:"pass",auth:"pass",end_to_end:"pass_synthetic_silence"},siyuan:{...base,tls:"pass",auth:"pass",delivery:"pass_test_entry_created",end_to_end:"pass"}}});
assert.equal(rendered.success,true);
assert.match(rendered.text,/合成静音请求已通过/);
assert.match(rendered.text,/测试条目已创建/);
rendered = report({mode:"end_to_end",providers:{qwen:{...base,tls:"pass",auth:"pass",end_to_end:"pass_synthetic_silence"},siyuan:{...base,delivery:"uncertain_do_not_repeat_automatically",end_to_end:"fail"}}});
assert.equal(rendered.success,false);
assert.equal(rendered.uncertain,true);
assert.match(rendered.text,/勿重复执行/);
assert.match(rendered.text,/千问：/);
assert.match(rendered.text,/思源：/);
assert.equal(report({mode:"tls",providers:{qwen:{...base,tls:"fail"}}}).success,false);
assert.match(report({mode:"validate",providers:{qwen:{...base,validation:"missing_credential"}}}).text,/尚未配置凭据/);
for (const invalid of [null,{}, {ok:true}, {mode:"tls",providers:{}}]) assert.equal(report(invalid).success,false);
console.log("PASS admin probe rendering: TLS/auth separation, both providers, success, partial failure, uncertain, malformed response");
